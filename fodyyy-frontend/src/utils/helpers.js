// Calculate estimated delivery time
export const calculateDeliveryTime = (orderTime, preparationTime, deliveryTime) => {
  const orderDate = new Date(orderTime);
  const totalMinutes = preparationTime + deliveryTime;
  return new Date(orderDate.getTime() + totalMinutes * 60000);
};

